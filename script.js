function setLanguage(language) {
    const selected = translations[language] ? language : "en";

    document.documentElement.lang = selected === "ua" ? "uk" : selected;
    currentLanguage.textContent = selected.toUpperCase();

    document.querySelectorAll("[data-i18n]").forEach(element => {
        const key = element.dataset.i18n;
        const translation = translations[selected][key];

        if (translation !== undefined) {
            element.textContent = translation;
        }
    });

    localStorage.setItem("hforked-language", selected);
    modal.hidden = true;
    refreshReleaseLanguage();
}

document.querySelectorAll("[data-language]").forEach(button => {
    button.addEventListener("click", () => {
        setLanguage(button.dataset.language);
    });
});

languageButton.addEventListener("click", () => {
    modal.hidden = false;
});

closeModal.addEventListener("click", () => {
    if (localStorage.getItem("hforked-language")) {
        modal.hidden = true;
    }
});

modal.addEventListener("click", event => {
    if (event.target === modal && localStorage.getItem("hforked-language")) {
        modal.hidden = true;
    }
});

const savedLanguage = localStorage.getItem("hforked-language");

if (savedLanguage && translations[savedLanguage]) {
    setLanguage(savedLanguage);
} else {
    setLanguage("en");
    modal.hidden = false;
}

